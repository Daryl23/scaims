// Run with NODE_PATH pointing to a directory containing Playwright.
// Network writes are stubbed so this test never creates an account.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const os = require('node:os');

(async () => {
    const browser = await chromium.launch({ channel: 'chrome', headless: true });
    try {
        const page = await browser.newPage({ viewport: { width: 1366, height: 900 } });
        const errors = [];
        page.on('pageerror', error => errors.push(error.message));
        let checks = 0;
        let submissions = 0;
        let duplicate = false;
        let finalSuccess = false;
        let finalPayload = '';
        const url = 'http://localhost/scaims/FARMERS%20UI/registration/registration_form.html';
        await page.route('**/check_rsbsa.php', route => {
            checks++;
            return route.fulfill({ body: duplicate ? 'duplicate' : 'unique' });
        });
        await page.route('**/complete_registration.php', route => {
            submissions++;
            finalPayload = route.request().postDataBuffer().toString();
            return route.fulfill({ status: finalSuccess ? 200 : 409, contentType: 'application/json', body: JSON.stringify({ success: finalSuccess, message: 'Username already exists.' }) });
        });
        await page.goto(url);
        assert.equal(await page.locator('#accountStep').isVisible(), false);
        assert.equal(await page.locator('label .required').count(), await page.locator('[required]').count());
        assert.equal(await page.locator('label[for="middleName"] .required').count(), 0);
        await page.locator('#nextButton').click();
        assert.equal(checks, 0, 'Invalid Part 1 must not make requests');
        const values = { surname: 'Tester', firstName: 'Sample', dob: '1990-01-01', contactNumber: '09123456789', address: 'Test Address', rsbsaNumber: '123456789012345' };
        for (const [id, value] of Object.entries(values)) await page.locator('#' + id).fill(value);
        await page.getByRole('radio', { name: 'Female', exact: true }).click();
        await page.locator('#barangay').selectOption('adya');
        await page.locator('#terms').check();
        duplicate = true;
        await page.locator('#nextButton').click();
        await page.locator('#registrationError').waitFor({ state: 'visible' });
        assert.equal(await page.locator('#personalStep').isVisible(), true);
        duplicate = false;
        await page.locator('#nextButton').click();
        await page.locator('#accountStep').waitFor({ state: 'visible' });
        assert.equal(await page.locator('#accountProgress').getAttribute('aria-current'), 'step');
        assert.equal(submissions, 0, 'Next must not save registration');
        await page.locator('#createAccountButton').click();
        assert.equal(submissions, 0, 'Invalid Part 2 must not submit');
        await page.locator('#username').fill('sample_tester');
        await page.locator('#password').fill('TestPassword1!');
        await page.locator('#confirmPassword').fill('Mismatch1!');
        await page.locator('#profileImage').setInputFiles({ name: 'profile.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j4ZkAAAAASUVORK5CYII=', 'base64') });
        await page.locator('#createAccountButton').click();
        assert.equal(submissions, 0, 'Password mismatch must not submit');
        await page.locator('#confirmPassword').fill('TestPassword1!');
        await page.locator('#backButton').click();
        assert.equal(await page.locator('#surname').inputValue(), 'Tester');
        assert.equal(await page.locator('#sex').inputValue(), 'female');
        assert.equal(await page.locator('#terms').isChecked(), true);
        await page.locator('#surname').fill('Updated');
        await page.locator('#nextButton').click();
        await page.locator('#accountStep').waitFor({ state: 'visible' });
        assert.equal(await page.locator('#username').inputValue(), 'sample_tester');
        assert.equal(await page.locator('#password').inputValue(), 'TestPassword1!');
        assert.equal(await page.locator('#profileImage').evaluate(el => el.files[0].name), 'profile.png');
        page.once('dialog', dialog => dialog.dismiss());
        await page.locator('#cancelButton').click();
        assert.equal(await page.locator('#username').inputValue(), 'sample_tester');
        await page.locator('#createAccountButton').click();
        await page.locator('#registrationError').waitFor({ state: 'visible' });
        assert.equal(submissions, 1);
        assert.match(finalPayload, /name="surname"\r\n\r\nUpdated/);
        assert.match(finalPayload, /name="profileImage"; filename="profile.png"/);
        assert.match(finalPayload, /name="terms"\r\n\r\non/);
        assert.equal(await page.locator('#password').inputValue(), 'TestPassword1!', 'Failure preserves entries');
        await page.screenshot({ path: path.join(os.tmpdir(), 'registration-step2-desktop.png'), fullPage: true });
        await page.setViewportSize({ width: 390, height: 844 });
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
        await page.screenshot({ path: path.join(os.tmpdir(), 'registration-step2-mobile.png'), fullPage: true });
        await page.locator('#backButton').click();
        await page.screenshot({ path: path.join(os.tmpdir(), 'registration-step1-mobile.png'), fullPage: true });
        page.once('dialog', dialog => dialog.dismiss());
        await page.locator('#cancelButton').click();
        assert.equal(await page.locator('#surname').inputValue(), 'Updated');
        await page.locator('#nextButton').click();
        await page.locator('#accountStep').waitFor({ state: 'visible' });
        finalSuccess = true;
        page.once('dialog', dialog => dialog.accept());
        await page.locator('#createAccountButton').click();
        await page.waitForURL('**/farmerLogin/farmerlogin.html');
        assert.equal(submissions, 2);
        await page.goto(url);
        page.once('dialog', dialog => dialog.accept());
        await page.locator('#cancelButton').click();
        await page.waitForURL('**/scaims/index.html');
        await page.goto('http://localhost/scaims/FARMERS%20UI/accountCreation/accountCreation.html');
        await page.waitForURL('**/registration/registration_form.html');
        assert.deepEqual(errors, []);
        console.log('PASS: step validation, required markers, duplicate check, Back preserves all values and upload, cancel stay/leave, final payload, retry, success redirect, mobile width, legacy URL.');
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
